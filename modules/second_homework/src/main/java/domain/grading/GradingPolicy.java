package domain.grading;

import java.math.BigDecimal;
import java.util.List;

/**
 * Правило итога (поведенческий паттерн «Стратегия»).
 *
 * <p>Как свести строки ведомости в одно число — решение курса, а не
 * калькулятора: в середине модуля нужна текущая успеваемость по уже
 * выставленным оценкам, в конце — итог по всему рубрикатору, а завтра
 * может появиться правило с отбрасыванием худшей оценки. Каждое правило —
 * отдельная реализация; {@link FinalGradeCalculator} и консоль при этом
 * не меняются.
 */
public interface GradingPolicy {

    /**
     * Короткий код правила для выбора и экспорта, например {@code full}.
     *
     * @return уникальный среди правил код
     */
    String code();

    /**
     * Описание правила для пользователя.
     *
     * @return описание, например «итог по всему рубрикатору»
     */
    String description();

    /**
     * Сводит строки ведомости в итог.
     *
     * @param lines строки ведомости студента по всем критериям рубрикатора
     * @return итог от 0 до {@link FinalGrade#MAX}
     */
    BigDecimal grade(List<GradeLine> lines);
}
