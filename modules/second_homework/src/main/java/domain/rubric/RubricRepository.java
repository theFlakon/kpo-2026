package domain.rubric;

/**
 * Хранилище рубрикатора — порт предметной области.
 *
 * <p>Интерфейс лежит рядом с агрегатом, а реализация — во внешнем слое
 * адаптеров: домен решает, что хранить, адаптер — как.
 */
public interface RubricRepository {

    /**
     * Возвращает рубрикатор курса.
     *
     * @return рубрикатор; пустой, если критериев ещё нет
     */
    Rubric get();

    /**
     * Сохраняет рубрикатор после изменения.
     *
     * @param rubric изменённый рубрикатор
     */
    void save(Rubric rubric);
}
