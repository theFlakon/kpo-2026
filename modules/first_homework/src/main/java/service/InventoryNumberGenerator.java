package service;

/**
 * Выдаёт инвентарные номера по возрастанию, начиная с единицы.
 *
 * <p>Интерфейса нет сознательно: реализация одна, а в тестах новый
 * экземпляр и так выдаёт предсказуемые 1, 2, 3. Абстракция здесь была бы
 * декоративной.
 *
 * <p>Генератор не знает о репозитории. Если объект попадёт на баланс
 * с номером в обход генератора, конфликт отсечёт репозиторий.
 *
 * <p>Не потокобезопасен: приложение однопоточное.
 */
public final class InventoryNumberGenerator {

    /** Первый выдаваемый номер. */
    private static final int FIRST_NUMBER = 1;

    /** Номер, который будет выдан следующим. */
    private int nextNumber = FIRST_NUMBER;

    /**
     * Выдаёт следующий номер.
     *
     * <p>Вызывать только тогда, когда объект точно будет создан:
     * выданный номер повторно не выдаётся.
     *
     * @return положительный номер, больший всех выданных ранее
     */
    public int next() {
        // Переполнение int (больше 2 млрд объектов) для парка нереально,
        // поэтому отдельно не обрабатывается.
        return nextNumber++;
    }
}