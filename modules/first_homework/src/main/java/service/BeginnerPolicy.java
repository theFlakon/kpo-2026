package service;

import domain.vehicle.Vehicle;

/**
 * Правило, по которому транспорт можно выдавать новичкам.
 *
 * <p>Интерфейс — реальная точка изменения: задание разрешает усложнить
 * правило. Новое правило добавляется новой реализацией, отчёты при этом
 * не меняются.
 */
// Один абстрактный метод: в тестах отчётов правило подменяется лямбдой.
@FunctionalInterface
public interface BeginnerPolicy {

    /**
     * Проверяет, можно ли выдавать транспорт новичку.
     *
     * @param vehicle проверяемый транспорт
     * @return {@code true}, если транспорт подходит новичку
     */
    boolean isSuitableForBeginner(Vehicle vehicle);

    /**
     * Описывает правило для пользователя, например «простота ≥ 6».
     *
     * <p>Метод с реализацией по умолчанию, поэтому интерфейс остаётся
     * функциональным и подменяется лямбдой.
     *
     * @return краткое описание правила
     */
    default String description() {
        return "по правилу парка";
    }
}