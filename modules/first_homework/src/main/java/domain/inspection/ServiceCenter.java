package domain.inspection;

/**
 * Сервис техосмотра: решает, принимать ли технику в парк.
 *
 * <p>Порт предметной области: правило «техника попадает в парк только
 * после техосмотра» принадлежит домену, а конкретные пороги — реализации
 * в слое сервисов. Сервис приёмки зависит только от этого интерфейса,
 * поэтому реализацию можно подменить через DI, в том числе в тестах.
 *
 * <p>Контракт для реализаций: метод не возвращает {@code null}
 * и не бросает исключений — заявка корректна по построению,
 * а отказ выражается через {@link InspectionResult#fail(String)}.
 */
@FunctionalInterface
public interface ServiceCenter {

    /**
     * Проводит техосмотр по заявке.
     *
     * @param request корректная заявка на приёмку
     * @return решение с непустой причиной
     */
    InspectionResult inspect(IntakeRequest request);
}